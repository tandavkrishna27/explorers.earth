/**
 * A production-shaped source for rehearsing backup and restore on a laptop.
 *
 *   npm run platform:recovery-fixture -- up      # prints the paths the next two commands need
 *   npm run platform:backup -- --environment local --reason manual \
 *       --candidate-digest <printed> --candidate-commit <printed>     # with EXPLORERS_BACKUP_ROOT=<printed>
 *   npm run platform:restore-drill -- --manifest <manifest> --identity <printed> --receipt <fresh temp dir>
 *   npm run platform:recovery-fixture -- down
 *
 * `up` starts a PostgreSQL 15 container labelled exactly like the postgres service
 * of deploy/production.compose.yml (under its own compose project, so it can never
 * be mistaken for the real one), migrates it with the real migration runner as a
 * superuser migrator named like production's, provisions the runtime login,
 * seeds data through the real canonical application, and writes a host-shaped
 * /opt/explorers into the system temp directory: production.env, the compose file,
 * two secret files, a local media root and a local backup destination. It also
 * generates a throwaway age identity there. Nothing it creates is inside the
 * repository, and nothing in it is a real secret.
 */
import { spawnSync } from "node:child_process";
import { createHash, randomBytes, randomInt } from "node:crypto";
import { copyFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const FIXTURE_PROJECT = "explorers-recovery-source";
const CONTAINER = `${FIXTURE_PROJECT}-postgres-1`;
const STATE = join(tmpdir(), "explorers-recovery-fixture.json");
const MIGRATOR = "explorers_migrator";
const RUNTIME = "explorers_runtime";
const DATABASE = "explorers";
const REPOSITORY = resolve(fileURLToPath(new URL("..", import.meta.url)));
const requireFromTunes = createRequire(join(REPOSITORY, "tunes", "package.json"));

function docker(args: string[], input?: string): string {
  const result = spawnSync("docker", args, { encoding: "utf8", windowsHide: true, input });
  if (result.status !== 0) throw new Error(`docker ${args[0]} failed: ${(result.stderr || "").trim().slice(0, 400)}`);
  return result.stdout.trim();
}

async function up(): Promise<void> {
  if (existsSync(STATE)) throw new Error(`a fixture is already up (${STATE}); run down first`);
  const root = join(tmpdir(), `explorers-recovery-host-${randomBytes(4).toString("hex")}`);
  for (const directory of ["secrets", "media", "destination", "keys"]) mkdirSync(join(root, directory), { recursive: true, mode: 0o700 });
  const migratorPassword = randomBytes(32).toString("base64url");
  const runtimePassword = randomBytes(32).toString("base64url");
  writeFileSync(join(root, "secrets", "db-migrator"), migratorPassword, { mode: 0o600 });
  writeFileSync(join(root, "secrets", "db-runtime"), runtimePassword, { mode: 0o600 });
  const port = randomInt(56_000, 61_000);
  writeFileSync(STATE, JSON.stringify({ root, port }), { mode: 0o600 });

  docker(["run", "--detach", "--name", CONTAINER,
    "--label", `com.docker.compose.project=${FIXTURE_PROJECT}`, "--label", "com.docker.compose.service=postgres",
    "--label", "com.explorers.recovery.fixture=true",
    "--env", `POSTGRES_USER=${MIGRATOR}`, "--env", `POSTGRES_DB=${DATABASE}`, "--env", "POSTGRES_PASSWORD_FILE=/run/secrets/db-migrator",
    "--mount", `type=bind,src=${join(root, "secrets", "db-migrator")},dst=/run/secrets/db-migrator,readonly`,
    "--publish", `127.0.0.1:${port}:5432`, "--tmpfs", "/var/lib/postgresql/data:rw,size=1073741824",
    "postgres:15-alpine"]);
  const pg = requireFromTunes("pg") as typeof import("../tunes/node_modules/@types/pg");
  const url = `postgresql://${MIGRATOR}:${migratorPassword}@127.0.0.1:${port}/${DATABASE}`;
  const owner = new pg.Pool({ connectionString: url, max: 4 });
  try {
    const deadline = Date.now() + 60_000;
    for (;;) {
      try { await owner.query("SELECT 1"); break; }
      catch (error) { if (Date.now() > deadline) throw error; await new Promise(done => setTimeout(done, 500)); }
    }
    const { migrateMusicDatabase } = await import("../tunes/server/db/migrate");
    const { provisionMusicRuntimeLogin } = await import("../tunes/server/db/music-runtime-role");
    const migrated = await migrateMusicDatabase(owner);
    await provisionMusicRuntimeLogin(owner, { loginRole: RUNTIME, password: runtimePassword });
    const authSecret = randomBytes(32).toString("hex");
    const seeded = await seed(owner, join(root, "media"), authSecret);

    const recipient = generateAgeIdentity(join(root, "keys"));
    const environment = [
      "# Generated by scripts/platform-recovery-fixture.ts. Every value is a throwaway.",
      `DB_NAME=${DATABASE}`, `DB_MIGRATOR_USER=${MIGRATOR}`, `DB_RUNTIME_USER=${RUNTIME}`,
      `DB_MIGRATOR_PASSWORD_FILE_HOST=${join(root, "secrets", "db-migrator")}`,
      `DB_RUNTIME_PASSWORD_FILE_HOST=${join(root, "secrets", "db-runtime")}`,
      "EXPLORERS_PUBLIC_ORIGIN=http://127.0.0.1:51474",
      `EXPLORERS_AUTH_SECRET=${authSecret}`,
      "GOOGLE_CLIENT_ID=fixture-google-client-id", "GOOGLE_CLIENT_SECRET=fixture-google-client-secret",
      `EXPLORERS_BACKUP_AGE_RECIPIENT=${recipient}`,
      `EXPLORERS_BACKUP_COMPOSE_PROJECT=${FIXTURE_PROJECT}`,
      `EXPLORERS_BACKUP_LOCAL_DESTINATION=${join(root, "destination")}`,
      `EXPLORERS_MEDIA_LOCAL_ROOT=${join(root, "media")}`,
    ].join("\n") + "\n";
    writeFileSync(join(root, "production.env"), environment, { mode: 0o600 });
    copyFileSync(join(REPOSITORY, "deploy", "production.compose.yml"), join(root, "production.compose.yml"));
    const commit = spawnSync("git", ["rev-parse", "HEAD"], { encoding: "utf8", cwd: REPOSITORY }).stdout.trim();
    process.stdout.write(`${JSON.stringify({
      backupRoot: root,
      identity: join(root, "keys", "identity.age"),
      destination: join(root, "destination"),
      candidateCommit: commit,
      // There is no image in a local rehearsal; this stands in for one and says so.
      candidateDigest: `sha256:${createHash("sha256").update(`local-recovery-fixture:${commit}`).digest("hex")}`,
      migrationMarker: migrated.currentId,
      seeded,
    }, null, 2)}\n`);
  } finally {
    await owner.end();
  }
}

/** Seeds through the real application where it can: the account is provisioned by
 *  /me for a real Better Auth session, exactly as a first sign-in does. */
async function seed(pool: import("../tunes/node_modules/@types/pg").Pool, mediaRoot: string, secret: string) {
  const { createCanonicalApp } = await import("../tunes/server/auth/canonicalApp");
  const { resolveExplorersAuthConfig } = await import("../tunes/server/auth/betterAuth");
  const { LocalObjectStorage } = await import("../tunes/server/services/objectStorage");
  const { signSessionCookie } = await import("./platform-restore-drill");
  const { createServer } = await import("node:http");
  const storage = new LocalObjectStorage(mediaRoot);
  const config = resolveExplorersAuthConfig({ EXPLORERS_PUBLIC_ORIGIN: "http://127.0.0.1:51474", EXPLORERS_AUTH_SECRET: secret,
    GOOGLE_CLIENT_ID: "fixture-google-client-id", GOOGLE_CLIENT_SECRET: "fixture-google-client-secret" });
  const composed = createCanonicalApp(pool, config, { mediaStorage: storage });
  const server = createServer(composed.app);
  await new Promise<void>(done => server.listen(0, "127.0.0.1", () => done()));
  const address = server.address() as import("node:net").AddressInfo;
  try {
    const context = await composed.auth.$context;
    const people = [];
    for (const [index, handle] of ["drillowner", "drillfriend"].entries()) {
      const userId = `recovery-fixture-${handle}`;
      await pool.query("INSERT INTO auth_user(id,name,email) VALUES($1,$2,$3)", [userId, `Recovery ${index}`, `${handle}@example.invalid`]);
      await pool.query("INSERT INTO auth_account(id,account_id,provider_id,user_id,updated_at) VALUES($1,$2,'google',$3,now())",
        [`fixture-account-${handle}`, `google-${handle}`, userId]);
      const session = await context.internalAdapter.createSession(userId, false);
      const me = await fetch(`http://127.0.0.1:${address.port}/api/explorers/v1/me`,
        { headers: { cookie: signSessionCookie(context.authCookies.sessionToken.name, session.token, secret) } });
      const body = await me.json() as { account?: { id?: string } };
      if (me.status !== 200 || !body.account?.id) throw new Error(`fixture sign-in failed: ${me.status}`);
      await pool.query(`UPDATE creator_accounts SET handle=$2, display_name=$3, account_type='Personal', public_profile=true,
        onboarding_status='complete' WHERE id=$1`, [body.account.id, handle, `Recovery ${index}`]);
      await pool.query("INSERT INTO account_presentation(account_id) VALUES($1) ON CONFLICT DO NOTHING", [body.account.id]);
      people.push({ handle, accountId: body.account.id });
    }
    const owner = people[0].accountId;
    const kinds: Record<string, string> = { places: "place", movies: "movie", books: "book", games: "game", apps: "app", products: "product", people: "person" };
    const { PUBLIC_RECOMMENDATION_CATEGORIES } = await import("../tunes/server/publicProfile/publicProfilePolicy");
    const recommendations: Record<string, string> = {};
    const { ExplorersRecommendationRepository } = await import("../tunes/server/repositories/explorersRecommendationRepository");
    const repository = new ExplorersRecommendationRepository(pool);
    for (const [order, category] of PUBLIC_RECOMMENDATION_CATEGORIES.entries()) {
      await pool.query(`INSERT INTO account_category_settings(account_id,category,is_public,display_order) VALUES($1,$2,true,$3)
        ON CONFLICT (account_id,category) DO UPDATE SET is_public=true`, [owner, category, order]);
      const kind = kinds[category];
      if (!kind) continue;
      const collectionRow = (await pool.query(`INSERT INTO collections(account_id,category,title,slug,display_order,visibility,publication_state)
        VALUES($1,$2,$3,$4,0,'public','published') RETURNING id,revision::text AS revision`, [owner, category, `Drill ${category}`, `drill-${category}`])).rows[0];
      const collection = collectionRow.id as string;
      if (category === "movies" || category === "apps" || category === "products") {
        // These public readers require their typed detail rows, so they go through the
        // real repository write path rather than bare inserts.
        const key = () => randomBytes(16).toString("hex");
        const entity = category === "movies"
          ? await repository.resolveMovieEntity(owner, { kind: "manual", category, details: { title: "Drill movie", mediaType: "movie" } }, key(), async () => undefined)
          : category === "apps"
            ? await repository.resolveAppEntity(owner, { kind: "manual", category, details: { title: "Drill app", appUrl: "https://example.invalid/app" } }, key())
            : await repository.resolveProductEntity(owner, { kind: "manual", category, details: { title: "Drill product", productUrl: "https://example.invalid/product" } }, key());
        const created = await repository.createRecommendation(owner, { category, entityId: entity.id, collectionId: collection,
          expectedCollectionRevision: Number(collectionRow.revision), publicationState: "published",
          note: { version: 1, format: "quill-html", html: `<p>Drill ${category}</p>` } }, key());
        recommendations[category] = created.id;
        continue;
      }
      const entity = (await pool.query("INSERT INTO entities(kind,title,origin) VALUES($1,$2,'manual') RETURNING id", [kind, `Drill ${kind}`])).rows[0].id;
      const recommendation = (await pool.query(`INSERT INTO recommendations(account_id,entity_id,category,user_rating,publication_state,note)
        VALUES($1,$2,$3,8,'published',$4) RETURNING id`,
      [owner, entity, category, JSON.stringify({ version: 1, format: "quill-html", html: `<p>Drill ${category}</p>` })])).rows[0].id;
      await pool.query("INSERT INTO collection_items(collection_id,recommendation_id,account_id,category,display_order) VALUES($1,$2,$3,$4,0)",
        [collection, recommendation, owner, category]);
      recommendations[category] = recommendation;
    }
    // One public attachment (served by the gated route) and one private upload (404 there).
    const media = [];
    for (const [label, attach] of [["public", true], ["private", false]] as const) {
      const bytes = randomBytes(2048);
      const id = (await pool.query("SELECT gen_random_uuid() AS id")).rows[0].id as string;
      const key = `local/${owner}/${id}`;
      await storage.put(key, bytes);
      const hash = createHash("sha256").update(bytes).digest();
      await pool.query(`INSERT INTO media_assets(id,account_id,purpose,status,mime_type,byte_size,content_sha256,ready_at)
        VALUES($1,$2,'recommendation','ready','image/png',$3,$4,now())`, [id, owner, bytes.length, hash]);
      await pool.query(`INSERT INTO media_objects(media_id,variant,storage_environment,object_key,mime_type,byte_size,content_sha256)
        VALUES($1,'original','local',$2,'image/png',$3,$4)`, [id, key, bytes.length, hash]);
      if (attach) await pool.query("INSERT INTO recommendation_media(recommendation_id,account_id,media_id,display_order) VALUES($1,$2,$3,0)",
        [recommendations.books, owner, id]);
      media.push({ label, id });
    }
    return { accounts: people.map(person => person.handle), categories: Object.keys(recommendations), media };
  } finally {
    await new Promise<void>(done => server.close(() => done()));
  }
}

/** age-keygen from the same pinned image the backup encrypts with. */
function generateAgeIdentity(directory: string): string {
  const { ensureAgeImage, AGE_IMAGE } = requireBackupModule();
  ensureAgeImage();
  docker(["run", "--rm", "--network", "none", "--volume", `${directory}:/keys`, "--entrypoint", "age-keygen", AGE_IMAGE, "-o", "/keys/identity.age"]);
  const recipient = /^# public key: (age1[0-9a-z]{58})$/m.exec(readFileSync(join(directory, "identity.age"), "utf8"))?.[1];
  if (!recipient) throw new Error("age-keygen produced no public key");
  return recipient;
}

let backupModule: typeof import("../tunes/deployment/platform-backup.mjs") | undefined;
function requireBackupModule() {
  if (!backupModule) throw new Error("backup module not loaded");
  return backupModule;
}

function down(): void {
  const state = existsSync(STATE) ? JSON.parse(readFileSync(STATE, "utf8")) as { root: string } : undefined;
  const id = spawnSync("docker", ["ps", "--all", "--quiet", "--filter", `name=^${CONTAINER}$`, "--filter", "label=com.explorers.recovery.fixture=true"],
    { encoding: "utf8", windowsHide: true }).stdout.trim();
  if (id) docker(["rm", "--force", "--volumes", id]);
  if (state?.root && resolve(state.root).startsWith(resolve(tmpdir())) && /explorers-recovery-host-[a-f0-9]{8}$/.test(state.root)) {
    rmSync(state.root, { recursive: true, force: true });
  }
  rmSync(STATE, { force: true });
  process.stdout.write(`${JSON.stringify({ down: true })}\n`);
}

const command = process.argv[2];
if (resolve(process.argv[1] ?? "") === resolve(fileURLToPath(import.meta.url))) {
  (async () => {
    backupModule = await import("../tunes/deployment/platform-backup.mjs");
    if (command === "up") await up();
    else if (command === "down") down();
    else throw new Error("usage: platform-recovery-fixture up|down");
  })().catch(error => { process.stderr.write(`platform-recovery-fixture: ${error instanceof Error ? error.message : error}\n`); process.exitCode = 1; });
}
